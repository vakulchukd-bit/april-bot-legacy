def detect_response_mode(text: str) -> str:
    t = text.lower()

    # ===== ССЫЛКИ (СНАЧАЛА — ВАЖНО) =====
    link_triggers = [
        "ссылка",
        "url",
        "линк",
        "дай ссылку",
        "короткую ссылку",
        "сократи ссылку",
        "сокращённую ссылку",
        "short link"
    ]

    for w in link_triggers:
        if w in t:
            return "link"

    # ===== КОПИРУЕМЫЕ ТЕКСТЫ =====
    copy_triggers = [
        "скопируй",
        "для копирования",
        "копировать",
        "дай текст",
        "готовый текст",
        "шаблон",
        "напиши текст",
        "заявление",
        "письмо",
        "документ",
        "сообщение клиенту",
        "напиши сообщение",
        "сделай текст",
        "напиши красиво"
    ]

    for w in copy_triggers:
        if w in t:
            return "copy"

    # ===== ОФОРМЛЕНИЕ =====
    format_triggers = [
        "красиво",
        "оформи",
        "сделай красиво",
        "оформи текст",
        "структурируй",
        "сделай читабельно",
        "разбей текст"
    ]

    for w in format_triggers:
        if w in t:
            return "format"

    # ===== ОБЫЧНЫЙ =====
    return "normal"
