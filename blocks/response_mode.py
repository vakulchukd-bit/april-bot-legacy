def detect_response_mode(text: str) -> str:

    t = text.lower().strip()

    # =====================================================
    # ===== LINK MODE
    # =====================================================

    link_triggers = [

        "ссылка",
        "url",
        "линк",
        "дай ссылку",
        "короткую ссылку",
        "сократи ссылку",
        "сокращённую ссылку",
        "short link"
    ]

    for w in link_triggers:

        if w in t:

            return "link"

    # =====================================================
    # ===== COPY / READY TEXT
    # =====================================================

    copy_triggers = [

        "скопируй",
        "для копирования",
        "копировать",
        "дай текст",
        "готовый текст",
        "шаблон",
        "напиши текст",
        "заявление",
        "письмо",
        "документ",
        "сообщение клиенту",
        "напиши сообщение",
        "сделай текст",
        "напиши красиво"
    ]

    for w in copy_triggers:

        if w in t:

            return "copy"

    # =====================================================
    # ===== FORMATTED / STRUCTURED
    # =====================================================

    format_triggers = [

        "красиво",
        "оформи",
        "сделай красиво",
        "оформи текст",
        "структурируй",
        "сделай читабельно",
        "разбей текст"
    ]

    for w in format_triggers:

        if w in t:

            return "format"

    # =====================================================
    # ===== VISUAL / CAMERA / IMAGE
    # =====================================================

    visual_triggers = [

        "что на фото",
        "что это",
        "что изображено",
        "что видишь",
        "посмотри",
        "проанализируй фото",
        "объясни фото",
        "что за место",
        "что за объект",
        "что это такое"
    ]

    for w in visual_triggers:

        if w in t:

            return "visual"

    # =====================================================
    # ===== SUPPORTIVE / HUMAN
    # =====================================================

    supportive_triggers = [

        "помоги",
        "не понимаю",
        "объясни",
        "что делать",
        "как быть",
        "подскажи",
        "посоветуй"
    ]

    for w in supportive_triggers:

        if w in t:

            return "supportive"

    # =====================================================
    # ===== SHORT CASUAL
    # =====================================================

    short_triggers = [

        "привет",
        "хай",
        "hello",
        "доброе утро",
        "добрый вечер",
        "как дела"
    ]

    for w in short_triggers:

        if w in t:

            return "casual"

    # =====================================================
    # ===== DEFAULT
    # =====================================================

    return "normal"
