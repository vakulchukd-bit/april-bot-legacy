def interpret_request(text: str):

    t = text.lower().strip()

    # =====================================================
    # ===== ГРАФИКИ =====
    # =====================================================

    if "парабола" in t:

        return {

            "type": "math",

            "normalized": "y = x**2"
        }

    if "синус" in t:

        return {

            "type": "math",

            "normalized": "y = np.sin(x)"
        }

    if "косинус" in t:

        return {

            "type": "math",

            "normalized": "y = np.cos(x)"
        }

    if "тангенс" in t:

        return {

            "type": "math",

            "normalized": "y = np.tan(x)"
        }

    # =====================================================
    # ===== ПРОСТЫЕ ГРАФИКИ =====
    # =====================================================

    if "прямая" in t:

        return {

            "type": "math",

            "normalized": "y = x"
        }

    # =====================================================
    # ===== КОД =====
    # =====================================================

    if "кнопка" in t:

        return {

            "type": "code",

            "normalized":
                "создай html кнопку с обработчиком клика"
        }

    if (
        "анимация" in t
        or "движется" in t
    ):

        return {

            "type": "code",

            "normalized":
                "создай html css анимацию"
        }

    # =====================================================
    # ===== INFORMATIONAL / SUPPORTIVE =====
    # =====================================================

    informational_words = [

        "информация",
        "данные",
        "что известно",
        "расскажи",
        "объясни",
        "что происходит",
        "почему",
        "как работает",
        "можешь помочь",
        "что можешь сказать"
    ]

    if any(w in t for w in informational_words):

        return {

            "type": "text",

            "normalized": text
        }

    # =====================================================
    # ===== WEB / LIVE CONTEXT =====
    # =====================================================

    live_words = [

        "погода",
        "новости",
        "курс",
        "сейчас",
        "где находится",
        "маршрут",
        "рейс",
        "карта"
    ]

    if any(w in t for w in live_words):

        return {

            "type": "text",

            "normalized": text
        }

    # =====================================================
    # ===== CONTINUATION / DIALOG =====
    # =====================================================

    continuation_words = [

        "дальше",
        "продолжим",
        "теперь",
        "еще",
        "вернемся"
    ]

    if any(w in t for w in continuation_words):

        return {

            "type": "text",

            "normalized": text
        }

    # =====================================================
    # ===== ЕСЛИ НИЧЕГО НЕ ПОНЯЛ =====
    # =====================================================

    return None
